import { Tutorial, studio } from './lib.mjs'
import { showConnectButton } from './seed-facebook.mjs'
const t = new Tutorial('facebook', { title: 'Bring in your Facebook leads', subtitle: 'Lead ads land in Leads by themselves', steps: 4 })
const s = await studio({ name: 'Mehta Studios', owner: 'Asha Mehta', skipSetup: true })
const p = await t.open(s)
await showConnectButton(p)
await t.goto('/lead-sources')
await t.start()
await t.titleCard()
const card = p.getByText('Facebook lead ads', { exact: true }).locator('xpath=ancestor::div[contains(@class,"rounded")][1]')
await t.step('Settings → Lead sources: the Facebook card', card, { hold: 1700, pad: 6 })
const btn = p.getByRole('link', { name: /Connect with Facebook/ })
await t.step('Tap Connect with Facebook', btn, { hold: 700 })
await t.point(btn)
await t.step('Log in, pick your Page, and you’re done', card, { hold: 700, pad: 6 })
await t.waitVoice(); await t.layer('spot', null); await t.layer('caption', null)
const leads = p.getByRole('link', { name: 'Leads', exact: true }).first()
await t.step('New leads appear in Leads, given to your team', leads, { hold: 2600 })
await t.endCard('Every Facebook lead, in one list')
await t.stop()
t.build()
