import { Tutorial, studio, sleep } from './lib.mjs'
import { withSpot, padEnd, frozen, sayHere } from './helpers.mjs'
import { seedProject } from './seed-q.mjs'
// Run with TZ=Asia/Kolkata so shoot times read as the studio sees them.
const t = new Tutorial('quotation', { title: 'Send your quotation', subtitle: 'Check it as the client sees it, then send the link', steps: 5 })
const s = await studio({ name: 'Mehta Studios', owner: 'Asha Mehta', skipSetup: true })
const { pid } = await seedProject(s)
const p = await t.open(s)
const h = withSpot(t)
await t.goto(`/projects/${pid}/quotation`)
await t.start()
await t.titleCard()
const scroll = async (dy, n = 6) => { for (let i = 0; i < n; i++) { await p.mouse.wheel(0, dy / n); await sleep(90) } await sleep(400) }
await p.mouse.move(700, 450)
await t.step('Your quotation fills in from the project', p.getByText('Prepared for Priya Sharma').locator('xpath=ancestor::div[1]'), { hold: 1600 })
await h.unspot()
await scroll(700)
await h.spot(p.locator('main table').nth(1))
await sleep(1500)
await h.spot(p.locator('.q-summary').first())
await sleep(1500)
await h.unspot(); await scroll(-900); await sleep(300)
const send = p.getByRole('button', { name: 'Send to client' }).first()
await t.step('Check it first: open “Send to client”', send, { hold: 1200 })
await h.click(send, { after: 700 })
const see = p.getByRole('button', { name: 'See it as the client' })
await t.step('“See it as the client” shows their exact copy', see, { hold: 1300 })
await h.click(see, { after: 300 }); await h.unspot(); await sleep(1500)
await p.locator('main').evaluate((e) => e.scrollTo({ top: 0 })); await sleep(700)
await sayHere(t, 'Opening it here is never counted as their view', p.getByText('This is what your client sees').locator('..'), 2200)
await h.unspot(); await scroll(900); await sleep(1600); await scroll(-900); await sleep(300)
const back = p.getByRole('button', { name: 'Back to my view' })
await t.step('Looks right? Go back to your view', back, { hold: 1200 })
await h.click(back, { after: 300 }); await h.unspot(); await sleep(1200)
await t.step('Send it: “Send to client”, then Copy link', send, { hold: 1200 })
await h.click(send, { after: 700 })
const copy = p.getByRole('button', { name: 'Copy link' })
await sleep(500)
await h.click(copy, { after: 300 }); await h.unspot(); await sleep(1300)
await t.say('Copied. Paste it on WhatsApp; the client can open it now.', p.getByRole('switch').first(), { hold: 2800 })
await t.endCard('A quotation your client can open in one tap')
await t.stop()
padEnd(t); frozen(t); t.build()
