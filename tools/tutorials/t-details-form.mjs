import { Tutorial, studio, sleep } from './lib.mjs'
import { seedDetailsForm, oneLinkAtATime } from './seed-details-form.mjs'
const t = new Tutorial('details-form', { title: 'Let the client fill in their details', subtitle: 'One link on WhatsApp; the project fills itself in', steps: 5 })
const s = await studio({ name: 'Mehta Studios', owner: 'Asha Mehta', skipSetup: true })
const d = await seedDetailsForm(s)
const p = await t.open(s)
await oneLinkAtATime(p)
await t.goto(`/projects/${d.projectId}`)
await t.start()
await t.titleCard()

const more = p.getByRole('button', { name: 'More actions' })
await t.step('Tap ⋯, then Send details form', more, { hold: 300 })
await t.click(more, { after: 500 })
await t.click(p.getByText('Send details form', { exact: true }), { after: 200 }); await t.layer('spot', null); await sleep(1500)

const dlg = p.getByRole('dialog')
const wa = dlg.getByRole('link', { name: /Send on WhatsApp/ })
await t.step('Send the link to Priya on WhatsApp', wa, { hold: 900 })
const url = await dlg.getByLabel('Details form link').inputValue()
await t.waitVoice(); await t.layer('caption', null); await t.layer('spot', null); await t.layer('hidePointer')
await t.goto(new URL(url).pathname)

const partner = p.locator('#cd-partner')
const about = partner.locator('xpath=ancestor::div[contains(@class,"grid")][1]')
await t.step('Her name and phone are in. She adds Rohan', about, { hold: 200, pad: 6 })
await t.type(partner, 'Rohan Mehta', { delay: 45 })

async function pickDate(i, typed) {
  await t.click(p.getByRole('button', { name: 'Date' }).nth(i), { after: 400 })
  await p.getByRole('textbox', { name: 'Type a date' }).pressSequentially(typed, { delay: 50 })
  await p.keyboard.press('Enter'); await sleep(400)
}
const events = p.getByText('Your events', { exact: true }).locator('xpath=..')
await events.evaluate((e) => e.scrollIntoView({ block: 'start' })); await sleep(500)
await t.step('Then each event, with its date and time', events, { hold: 200, pad: 6 })
await t.click(p.getByRole('button', { name: 'Haldi', exact: true }), { after: 300 })
await pickDate(0, '11/12/2026')
await t.click(p.getByRole('button', { name: 'Add another event' }), { after: 400 })
await t.click(p.getByRole('button', { name: 'Wedding', exact: true }), { after: 300 })
await pickDate(1, '12/12/2026')
await t.click(p.getByRole('button', { name: 'Start time' }).nth(1), { after: 400 })
await p.getByRole('textbox', { name: 'Type a time' }).pressSequentially('7:00 pm', { delay: 50 })
await p.keyboard.press('Enter'); await sleep(400)
await t.click(p.getByRole('combobox', { name: 'Hours' }).nth(1), { after: 300 })
await t.click(p.getByRole('option', { name: '5 h', exact: true }), { after: 300 })

const send = p.getByRole('button', { name: 'Send', exact: true })
await send.evaluate((e) => e.scrollIntoView({ block: 'center' })); await sleep(400)
await t.step('She taps Send', send, { hold: 200 })
await t.click(send, { after: 200 }); await t.layer('spot', null); await sleep(1300)
await t.layer('hidePointer')
await p.getByText(/^Thank you, Priya/).waitFor(); await sleep(700)
await t.say('Thank you, Priya! The studio has her details', p.locator('h1').first().locator('xpath=ancestor::div[contains(@class,"rounded")][1]'), { hold: 900, pad: 8 })
await t.layer('caption', null); await t.layer('spot', null)

await t.goto(`/projects/${d.projectId}?tab=shoots`)
await p.mouse.wheel(0, 320); await sleep(600)
await t.say('Her days are on your Shoots tab, ready for the team', null, { hold: 2000 })
await t.endCard('She types it once. The project fills itself in')
await t.stop()
t.build()
