import { Tutorial, studio, sleep, WEB } from './lib.mjs'
import { seedEnquiryStudio, sendEnquiry } from './seed-enquiry-form.mjs'
const t = new Tutorial('enquiry-form', { title: 'Your enquiry form and QR code', subtitle: 'Every enquiry lands in Leads by itself', steps: 5 })
const s = await studio({ name: 'Mehta Studios', owner: 'Asha Mehta', skipSetup: true })
await seedEnquiryStudio(s)
const p = await t.open(s)
await t.ctx.grantPermissions(['clipboard-read', 'clipboard-write'], { origin: WEB })
await t.goto('/enquiry-forms')
await t.start()
await t.titleCard()

const add = p.getByRole('button', { name: 'Add form' }).first()
await t.step('Settings → Forms: tap Add form', add, { hold: 500 })
await t.click(add, { after: 1000 })
const dlg = p.getByRole('dialog')
const site = dlg.getByRole('radio', { name: /Your website/ })
await t.step('Your website, or a QR for a vendor', dlg.getByRole('radiogroup'), { hold: 600, pad: 6 })
await t.click(site, { after: 600 })
await t.click(dlg.getByRole('button', { name: 'Make the form' }), { after: 150 })
await t.layer('spot', null); await sleep(1000)

const edit = p.getByRole('button', { name: 'Edit form' })
await edit.waitFor(); await p.waitForLoadState('networkidle').catch(() => {}); await sleep(500)
await t.step('Edit form: your words, and what it asks', edit, { hold: 1200 })
await t.click(edit, { after: 100 })
await t.layer('spot', null); await sleep(900)
const b = p.getByRole('dialog')
const head = b.locator('#fb-title')
await t.type(head, 'Tell us about your wedding', { delay: 45 })
await t.type(b.locator('#fb-intro'), 'Weddings across Pune and Mumbai since 2014', { delay: 30 })
await t.click(b.getByRole('radiogroup', { name: 'Budget' }).getByRole('radio', { name: 'Required' }), { after: 500 })
await t.click(b.getByRole('radiogroup', { name: 'Email' }).getByRole('radio', { name: 'Ask' }), { after: 700 })
const look = b.getByText('How it looks', { exact: true }).locator('xpath=..')
await t.say('The form beside it changes as you go', look, { hold: 1000, pad: 4 })

const tone = b.getByRole('button', { name: 'rose', exact: true })
await t.step('Pick a button colour, then Save form', tone.locator('xpath=../..'), { hold: 300 })
await t.click(tone, { after: 900 })
await t.click(b.getByRole('button', { name: 'Save form' }), { after: 150 })
await t.layer('spot', null); await sleep(1600)

const copy = p.getByRole('button', { name: 'Copy code' })
await t.step('Copy code, and paste it into your website', copy.locator('xpath=ancestor::div[contains(@class,"rounded")][1]'), { hold: 300, pad: 4 })
await t.click(copy, { after: 1600 })

await sendEnquiry(s)
await t.layer('spot', null); await t.layer('caption', null); await t.layer('hidePointer')
await t.click(p.getByRole('link', { name: 'Leads', exact: true }).first(), { after: 100 })
await t.layer('hidePointer')
await p.waitForLoadState('networkidle').catch(() => {}); await sleep(1800)
const lead = p.getByText('Priya Sharma').first()
await t.say('Priya’s enquiry is already in Leads', lead.locator('xpath=ancestor::*[self::li or self::article or self::a or contains(@class,"rounded")][1]'), { hold: 3000, pad: 6 })
await t.endCard('Every enquiry lands in Leads by itself')
await t.stop()
t.build()
