import { Tutorial, sleep } from './lib.mjs'
import { setup, kit, quickToPrice } from './wiz.mjs'
const t = new Tutorial('project-billing', { title: 'Project step 4: the price', subtitle: 'The package price and any advance paid', steps: 4 })
const { p } = await setup(t)
await quickToPrice(p)
const k = kit(t, p)
const { main } = k

await t.start()
await t.titleCard(1800)
const price = p.getByPlaceholder('150000', { exact: true })
await t.step('Type the package price', price, { hold: 800 })
await k.key(price, '150000', 70)
await sleep(300)
await k.spot(main.getByText('Project total').first().locator('xpath=../..'), 8)
await sleep(1200)

const adv = p.getByPlaceholder('50000', { exact: true })
await t.step('Already paid? Add the advance (optional)', adv, { hold: 800 })
await k.key(adv, '50000', 70)
await sleep(300)
await sleep(500)

await t.step('Then Next: Review', k.next, { hold: 600 })
await k.tap(k.next, { after: 200 })
await t.layer('spot', null)
await main.getByText('Step 5 of 5').waitFor({ timeout: 5000 }).catch(() => {})
await sleep(500)
await t.say('The balance to collect is worked out', null, { hold: 0 })
await k.spot(main.getByText('Received ₹50,000').first().locator('xpath=..'), 10)
await sleep(1600)

const create = p.getByRole('button', { name: 'Create project' })
await t.step('Press Create project', create, { hold: 1200 })
await t.layer('ripple'); await sleep(200)
await t.layer('spot', null)
await create.click()
await p.waitForURL(/quotation/, { timeout: 15000 })
await main.getByText('PROJECT QUOTATION').first().waitFor({ timeout: 10000 })
await sleep(900)
await t.layer('hidePointer')
await t.say('Done: the quotation opens, ready to send', null, { hold: 2400 })
await t.endCard('Price it once, the balance keeps itself')
await t.stop()
t.build()
