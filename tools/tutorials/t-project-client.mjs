import { Tutorial, studio, sleep, api } from './lib.mjs'
const t = new Tutorial('project-client', { title: 'Project step 1: who it’s for', subtitle: 'Name the project and pick the client', steps: 3 })
const s = await studio({ name: 'Mehta Studios', owner: 'Asha Mehta', skipSetup: true })
await api('/clients', { token: s.token, method: 'POST', body: { name: 'Priya Sharma', phone: '9876501234' } })
await api('/clients', { token: s.token, method: 'POST', body: { name: 'Ravi Kumar', phone: '9812345670' } })
const p = await t.open(s)
await t.goto('/projects/new')
const main = p.locator('main')
const nameIn = p.getByPlaceholder('e.g. Aanya & Rahul Wedding')
await nameIn.waitFor({ timeout: 10000 })
await t.start()
await t.titleCard(2300)
await t.step('Name the project', nameIn, { hold: 800 })
await t.type(nameIn, "Priya & Rahul's Wedding", { delay: 40 })
const search = main.getByPlaceholder('Search by name or phone…')
const tabs = main.getByRole('button', { name: 'New client' }).first()
await t.step('Pick the client, or add a new one', tabs, { hold: 300 })
async function fit() {
  const a = await main.getByText('Client', { exact: true }).first().boundingBox()
  const sr = await search.boundingBox()
  const last = main.getByText('Priya Sharma').last()
  const b = await last.boundingBox()
  const bottom = Math.max(sr.y + sr.height, b.y + b.height + 14)
  await t.layer('spot', { x: sr.x, y: a.y, width: sr.width, height: bottom - a.y }, 8)
}
await fit()
await sleep(1200)
await t.type(search, 'Priya', { delay: 60 })
await sleep(400)
await fit()
await sleep(300)
const pick = main.getByText('Priya Sharma').first()
await t.click(pick, { after: 900 })
const next = p.getByRole('button', { name: /^Next/ })
await t.step('Press Next: Event days', next, { hold: 1100 })
await t.point(next); await t.layer('ripple'); await sleep(200)
await t.layer('spot', null)
await next.click()
await main.getByText('Step 2 of 5').waitFor({ timeout: 8000 })
await sleep(700)
await t.layer('hidePointer')
await t.say('Done. Now add the days you shoot.', main.getByText('Add your functions').first().locator('xpath=..'), { hold: 2800 })
await t.endCard('One client, one project, all in one place', 2800)
await t.stop()
t.build()
