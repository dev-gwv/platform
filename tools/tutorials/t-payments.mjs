import { Tutorial, studio, sleep } from './lib.mjs'
import { seedPayments } from './seeds.mjs'
const t = new Tutorial('payments', { title: 'Record a payment', subtitle: 'See what is due, and mark money in', steps: 5 })
const s = await studio({ name: 'Mehta Studios', owner: 'Asha Mehta', skipSetup: true })
await seedPayments(s)
const p = await t.open(s)
await t.goto('/billing/payments')
await t.start()
await t.titleCard()
const overdue = p.getByRole('button', { name: /Overdue/ }).first()
const tiles = p.locator('div').filter({ has: overdue }).filter({ hasText: 'Received ·' }).last()
await t.step('Late, due soon, later and received, at a glance', tiles, { hold: 2600 })
await t.step('Tap Overdue to see who owes you', overdue, { hold: 1100 })
await t.click(overdue, { after: 1200 })
const open = p.getByText('Open invoice').first()
await t.say('Priya’s advance is 5 days late', p.locator('main div').filter({ hasText: /days late/ }).filter({ has: open }).last(), { hold: 1800 })
await t.step('Open the invoice', open, { hold: 1000 })
await t.click(open, { after: 100 }); await t.layer('spot', null); await sleep(1400)
const add = p.getByRole('button', { name: 'Add payment from client' })
await t.step('Tap “Add payment from client”', add, { hold: 1100 })
await t.click(add, { after: 100 }); await t.layer('spot', null); await sleep(1200)
const dlg = p.getByRole('dialog')
await t.step('Record payment: the amount is in. Pick UPI, add the UTR', dlg, { hold: 1000, pad: 4 })
await t.click(dlg.getByRole('button', { name: 'UPI' }).or(dlg.getByText('UPI', { exact: true })).first(), { after: 400 })
await t.type(dlg.getByPlaceholder('UTR / cheque no.'), '427815093361', { delay: 60 })
await sleep(300)
await t.click(dlg.getByRole('button', { name: 'Save payment' }), { after: 150 })
await t.layer('spot', null); await t.layer('caption', null)
await sleep(2000)
await t.say('Paid. Now back to Money → Payments', null, { hold: 1000 })
await t.click(p.getByRole('link', { name: 'Money', exact: true }).first(), { after: 1800 })
await t.layer('hidePointer')
await t.say('Counted in Received, and nothing is overdue', tiles, { hold: 3000 })
await t.endCard('Know who has paid, and who has not')
await t.stop()
t.build()
