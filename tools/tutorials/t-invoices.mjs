import { Tutorial, studio, sleep, WEB } from './lib.mjs'
import { withSpot, padEnd, frozen, sayHere } from './helpers.mjs'
import { seedProject } from './seed-q.mjs'
// Run with TZ=Asia/Kolkata.
const t = new Tutorial('invoices', { title: 'Send an invoice', subtitle: 'Made from the project, shared as a link', steps: 6 })
const s = await studio({ name: 'Kapoor Films Invoices', owner: 'Asha Mehta', skipSetup: true })
const { pid } = await seedProject(s)
const p = await t.open(s)
await t.ctx.grantPermissions(['clipboard-read', 'clipboard-write'], { origin: WEB })
const h = withSpot(t)
await t.goto(`/projects/${pid}?tab=billing`)
await p.getByText('Money in and out').scrollIntoViewIfNeeded()
await p.mouse.wheel(0, -120); await sleep(600)
await t.start()
await t.titleCard()
const create = p.locator('main').getByRole('button', { name: 'Create invoice' }).first()
await t.step('On the project’s Billing, tap “Create invoice”', create, { hold: 1500 })
await h.click(create, { after: 300 }); await h.unspot(); await sleep(1500)
const union = async (...ls) => { const rs = (await Promise.all(ls.map((l) => l.boundingBox().catch(() => null)))).filter(Boolean)
  const x = Math.min(...rs.map((r) => r.x)), y = Math.min(...rs.map((r) => r.y))
  return { x, y, width: Math.max(...rs.map((r) => r.x + r.width)) - x, height: Math.max(...rs.map((r) => r.y + r.height)) - y } }
const cust = p.getByText('Customer name').first().locator('xpath=ancestor::div[1]')
const proj = p.getByRole('combobox').filter({ hasText: 'Priya & Rahul Wedding' }).first()
await t.step('Priya and her project are already filled in', cust, { hold: 1400, pad: 6 })
await t.layer('spot', await union(cust, proj), 6); await t.point(proj); await sleep(1300)
const subject = p.getByPlaceholder(/Let your customer know/)
await h.retype(subject, 'Wedding coverage, 11–13 Dec', 50); await h.unspot(); await sleep(300)
const line = p.locator('input').and(p.locator('[value*="Package"]')).first()
const rate = p.locator('input').and(p.locator('[value="285000"]')).first()
await t.step('The booked package is already on the first line', null, { hold: 0 })
await t.layer('spot', await union(line, rate), 8); await t.point(rate); await sleep(1600)
await t.layer('caption', '₹2,85,000, the price Priya booked at'); await sleep(2300)
const save = p.getByRole('button', { name: 'Save and send' })
await t.step('Press “Save and send”', save, { hold: 1200 })
await h.click(save, { after: 200 }); await h.unspot(); await t.layer('caption', null); await sleep(1600)
const row = p.locator('main').getByText('INV-0001').first()
await t.layer('spot', await p.locator('[data-sonner-toast]').filter({ hasText: 'INV-0001 saved' }).first().boundingBox().catch(() => null), 6)
await t.layer('caption', 'Saved as INV-0001'); await sleep(1700)
await row.evaluate((e) => e.scrollIntoView({ block: 'center', behavior: 'smooth' })); await sleep(900)
const rowBox = p.locator('main div').filter({ hasText: 'INV-0001' }).filter({ has: p.getByRole('button', { name: 'Record' }) }).last()
await sayHere(t, 'It is listed on the project, marked Sent', rowBox, 2000, 6)
await t.step('Open it to share it', row, { hold: 1100 })
await h.click(row, { after: 200 }); await h.unspot(); await sleep(1800)
await sayHere(t, 'This is the invoice Priya gets', p.locator('main').getByText('BALANCE DUE').first().locator('xpath=ancestor::div[4]'), 2200, 6)
const link = p.getByRole('button', { name: 'Client link' })
await t.step('“Client link” copies a link she can open', link, { hold: 1300 })
await h.click(link, { after: 200 }); await h.unspot(); await sleep(1600)
await t.layer('hidePointer')
await sayHere(t, 'Copied. Paste it on WhatsApp; no login needed', p.locator('[data-sonner-toast]').filter({ hasText: 'Link copied' }).first(), 2800, 6)
await t.endCard('An invoice on Priya’s phone in a minute')
await t.stop()
padEnd(t); frozen(t); t.build()
