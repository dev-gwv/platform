import { Tutorial, studio, sleep } from './lib.mjs'
import { withSpot, padEnd, frozen, sayHere } from './helpers.mjs'
import { seedExpenses } from './x3/seed-exp.mjs'
// Run with TZ=Asia/Kolkata.
const t = new Tutorial('expenses', { title: 'Add an expense', subtitle: 'Every cost on the right project, and who paid it', steps: 6 })
const s = await studio({ name: 'Kapoor Films Expenses', owner: 'Asha Mehta', skipSetup: true })
await seedExpenses(s)
const p = await t.open(s)
const h = withSpot(t)
await t.goto('/company-expenses')
await t.start()
await t.titleCard()
const tiles = p.locator('main').getByText('Spent this month').locator('xpath=ancestor::div[3]')
const add = p.locator('main').getByRole('button', { name: 'Add expense' }).first()
await t.step('Tap “Add expense”', add, { hold: 1300 })
await h.click(add, { after: 300 }); await h.unspot(); await sleep(900)
const d = p.getByRole('dialog').last()
const amount = d.locator('input').first()
await t.step('Type the amount', amount, { hold: 1000 })
await h.type(amount, '8500', { delay: 110 }); await sleep(500)
const combos = d.getByRole('combobox')
await t.step('Pick a category from the list', combos.nth(0), { hold: 1000 })
await h.click(combos.nth(0), { after: 400 }); await h.unspot(); await sleep(900)
await t.click(p.getByRole('option', { name: 'Travel', exact: true }), { after: 400 })
await h.type(d.getByPlaceholder(/Cab to venue/), 'Cab and hotel for the Haldi team', { delay: 45 }); await h.unspot(); await sleep(400)
await t.step('Who paid? Ravi paid from his own pocket', combos.nth(1), { hold: 1000 })
await h.click(combos.nth(1), { after: 400 }); await h.unspot(); await sleep(700)
await t.click(p.getByRole('option', { name: 'Ravi Kumar' }), { after: 500 })
await sayHere(t, 'So it shows under “To reimburse” until he is paid back', d.getByText(/From their own pocket/), 2200)
await t.step('Put it on the project it belongs to', combos.nth(2), { hold: 1000 })
await h.click(combos.nth(2), { after: 400 }); await h.unspot(); await sleep(700)
await t.click(p.getByRole('option', { name: 'Priya & Rahul Wedding' }), { after: 600 })
const save = d.getByRole('button', { name: 'Add expense' })
await t.step('Press “Add expense” to save it', save, { hold: 1200 })
await h.click(save, { after: 200 }); await h.unspot(); await t.layer('caption', null); await sleep(1800)
await t.layer('hidePointer')
await t.say('Counted: this month is now ₹29,000', tiles, { hold: 2600 })
await t.say('And ₹8,500 is owed back to Ravi', p.locator('main').getByText('To reimburse').locator('xpath=ancestor::div[2]'), { hold: 2200 })
await t.say('The row says the project and who to pay back', p.locator('main tbody tr').filter({ hasText: 'Haldi' }), { hold: 2400 })
await t.endCard('Every rupee spent, on the right project')
await t.stop()
padEnd(t); frozen(t); t.build()
