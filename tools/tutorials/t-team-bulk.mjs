import { Tutorial, studio, sleep } from './lib.mjs'
const t = new Tutorial('team-bulk', { title: 'Add your whole team at once', subtitle: 'The people who shoot and edit with you', steps: 5 })
const s = await studio({ name: 'Mehta Studios', owner: 'Asha Mehta', skipSetup: false })
const p = await t.open(s)
await t.start()
await t.titleCard()
await t.step('Tap “Add your team”', p.getByRole('button', { name: 'Add your team' }).last())
await t.layer('spot', null)
await t.click(p.getByRole('button', { name: 'Add your team' }).last(), { after: 1500 })
const name1 = p.getByPlaceholder('Full name').nth(0)
await t.step('One row per person: name and mobile', p.locator('table').first(), { hold: 900 })
await t.type(name1, 'Ravi Kumar')
await t.type(p.getByPlaceholder('Mobile').nth(0), '9876543210')
await t.type(p.getByPlaceholder('Full name').nth(1), 'Neha Singh')
await t.type(p.getByPlaceholder('Mobile').nth(1), '9811122233')
await sleep(700)
await t.step('Give a login: any email works, it is just a username', p.getByPlaceholder('Blank = no login').nth(0), { hold: 900 })
await t.type(p.getByPlaceholder('Blank = no login').nth(0), `ravi${Math.floor(Math.random()*9000+1000)}@mehta.studio`)
await t.type(p.getByPlaceholder('6+ characters').nth(1), 'ravi2026')
await sleep(500)
const works = p.getByRole('combobox', { name: 'Row 2 works as' })
await t.step('Freelancer? Switch them to Per shoot', works, { hold: 1200 })
await t.click(works, { after: 700 }); await t.click(p.getByRole('option', { name: 'Per shoot' }), { after: 1000 })
await t.step('Add them, and you are done', p.getByRole('button', { name: /Add \d+ people/ }), { hold: 1100 })
await t.click(p.getByRole('button', { name: /Add \d+ people/ }), { after: 200 })
await t.layer('spot', null)
await sleep(2400)
await t.say('Your team is in. Next: your first client.', null, { hold: 2000 })
await t.endCard('Your team, ready in a minute')
await t.stop()
t.build()
