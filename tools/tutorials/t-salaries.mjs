import { Tutorial, studio, sleep } from './lib.mjs'
import { withSpot, frozen, sayHere } from './helpers.mjs'
import { seedSalaries } from './seed-salaries.mjs'
// Run with TZ=Asia/Kolkata. September is the month paid (worked out on 6 Oct).
const t = new Tutorial('salaries', { title: 'Salaries and payslips', subtitle: 'Set a salary, work out the month, pay and send the payslip', steps: 6 })
const s = await studio({ name: 'Mehta Studios', owner: 'Asha Mehta', skipSetup: true })
await seedSalaries(s)
const p = await t.open(s)
const h = withSpot(t)
await t.goto('/employees')
await t.start()
await t.titleCard()

const edit = p.getByTitle('Edit Ravi Kumar').first()
await t.step('Team → People. Tap Edit on Ravi', edit, { hold: 300 })
await h.click(edit, { after: 300 }); await h.unspot(); await sleep(1100)

const dlg = p.getByRole('dialog')
const type = dlg.getByRole('combobox').filter({ hasText: 'Select…' })
await dlg.getByText('Payment & Work Type').evaluate((e) => e.scrollIntoView({ block: 'start' })); await sleep(700)
await t.step('Payment type: Monthly Salaried, then his salary', type, { hold: 300 })
await h.click(type, { after: 500 })
await t.click(p.getByRole('option', { name: 'Monthly Salaried' }), { after: 700 })
const salary = dlg.getByText('Monthly Salary / Retainer (₹)').locator('xpath=..').locator('input')
await h.type(salary, '22000', { delay: 90 }); await h.spot(salary); await sleep(500)
await h.click(dlg.getByRole('button', { name: 'Save changes' }), { after: 300 }); await h.unspot(); await sleep(900)

const pay = p.getByRole('link', { name: 'Pay', exact: true }).first()
await t.step('Pay → Payroll. Pick September, tap Work out pay', pay, { hold: 300 })
await h.click(pay, { after: 300 }); await h.unspot(); await sleep(400)
// Pay opens on Team payouts; Payroll is the next tab.
await h.click(p.getByRole('link', { name: 'Payroll', exact: true }).or(p.getByRole('tab', { name: 'Payroll', exact: true })).first(), { after: 300 }); await h.unspot()
await p.getByRole('button', { name: 'Work out pay' }).waitFor({ timeout: 10000 }); await sleep(700)
await h.click(p.locator('main').getByRole('combobox').first(), { after: 500 })
await t.click(p.getByRole('option', { name: 'September' }), { after: 700 })
await h.click(p.getByRole('button', { name: 'Work out pay' }), { after: 300 }); await h.unspot()
await p.locator('tr').filter({ hasText: 'Neha Joshi' }).waitFor({ timeout: 10000 }); await sleep(900)
await t.layer('hidePointer')
await sayHere(t, 'Days in, unpaid leave and absences are counted', p.locator('tr').filter({ hasText: 'Neha Joshi' }), 1500)

const approve = p.getByRole('button', { name: 'Approve' })
await t.step('Each line checked? Approve the month', approve, { hold: 300 })
await h.click(approve, { after: 300 }); await h.unspot(); await sleep(700)
await h.click(p.getByRole('dialog').getByRole('button', { name: 'Approve' }), { after: 300 }); await h.unspot(); await sleep(1500)

const markPaid = p.locator('tr').filter({ hasText: 'Ravi Kumar' }).getByRole('button', { name: 'Mark paid' })
await t.step('Pay Ravi: his UPI is right there', markPaid, { hold: 300 })
await h.click(markPaid, { after: 300 }); await h.unspot(); await sleep(900)
const pdlg = p.getByRole('dialog')
await h.type(pdlg.getByPlaceholder('UTR or cheque no.'), '527316048219', { delay: 60 }); await sleep(300)
await h.click(pdlg.getByRole('button', { name: 'Mark paid' }), { after: 300 }); await h.unspot(); await sleep(1500)

const slip = p.getByRole('link', { name: 'Payslip for Ravi Kumar' })
await t.step('Open his payslip', slip, { hold: 300 })
await h.click(slip, { after: 300 }); await h.unspot()
await p.getByText('NET PAY', { exact: false }).first().waitFor({ timeout: 10000 }); await sleep(1200)
await t.layer('hidePointer')
await sayHere(t, 'Paid, and Ravi sees it on his own login', p.locator('main'), 1700, 2)
await t.endCard('Salaries paid right, every month')
await t.stop()
frozen(t); t.build()
