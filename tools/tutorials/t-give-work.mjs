import { Tutorial, studio, sleep } from './lib.mjs'
import { seedGiveWork } from './seeds.mjs'
const t = new Tutorial('give-work', { title: 'Give editing work', subtitle: 'Hand a film to an editor in one step', steps: 5 })
const s = await studio({ name: 'Mehta Studios', owner: 'Asha Mehta', skipSetup: true })
const d = await seedGiveWork(s)
const p = await t.open(s)
await t.goto(`/projects/${d.projectId}`)
await t.start()
await t.titleCard()
const post = p.getByRole('button', { name: 'Post-Production' }).or(p.getByRole('tab', { name: 'Post-Production' })).first()
await t.step('Open the project’s Post-Production tab', post, { hold: 1300 })
await t.click(post, { after: 1400 })
const start = p.getByRole('button', { name: 'Start editing' }).first()
await t.step('Nobody on the teaser yet? Tap Start editing', start, { hold: 1300 })
await t.click(start, { after: 1300 })
const list = p.getByRole('listbox', { name: 'People' })
await t.step('Editors are listed with how much they already have', list, { hold: 2000 })
await t.click(p.getByRole('option', { name: /Kavya Iyer/ }), { after: 900 })
const due = p.locator('#give-due')
await t.step('The due date is filled in. Add a line of brief', due.locator('xpath=ancestor::div[contains(@class,"grid")][1]'), { hold: 1200 })
await t.type(p.locator('#give-brief'), 'Upbeat song, keep the pheras and the baraat entry', { delay: 40 })
await sleep(400)
const go = p.getByRole('button', { name: /Start editing with/ })
await t.step('Tap “Start editing with Kavya”', go, { hold: 1300 })
await t.click(go, { after: 150 }); await t.layer('spot', null); await t.layer('caption', null); await sleep(1500)
const card = p.locator('li').filter({ has: p.getByText('Wedding Teaser', { exact: true }) }).first()
await card.evaluate((e) => e.scrollIntoView({ block: 'start' })); await p.mouse.wheel(0, -260); await sleep(900)
await t.layer('hidePointer')
await t.say('Now in Editing, on Kavya’s own list under My work', card, { hold: 2800, pad: 6 })
await t.endCard('Every edit has an owner and a date')
await t.stop()
t.build()
