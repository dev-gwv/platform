import { Tutorial, studio, sleep } from './lib.mjs'
const t = new Tutorial('attendance', { title: 'Turn on attendance', subtitle: 'Where your studio is, and when the day starts', steps: 5 })
const s = await studio({ name: 'Mehta Studios', owner: 'Asha Mehta', skipSetup: true })
const p = await t.open(s)
await t.goto('/settings/attendance-location')
await t.start()
await t.titleCard()
const on = p.getByRole('button', { name: 'Turn on attendance' })
await t.step('Settings → Attendance. It is off until you turn it on', on, { hold: 1500 })
await t.click(on, { after: 100 }); await t.layer('spot', null); await sleep(1100)
const paste = p.getByRole('button', { name: 'Paste a Google Maps link' })
await t.step('Paste your studio’s Google Maps link', paste, { hold: 1100 })
await t.click(paste, { after: 600 })
await t.type(p.getByPlaceholder('https://maps.app.goo.gl/…'), 'https://www.google.com/maps/place/Mehta+Studios/@19.0596,72.8295,17z', { delay: 25 })
await t.click(p.getByRole('button', { name: 'Use this link' }), { after: 1100 })
const radius = p.getByRole('button', { name: '100 m', exact: true }).or(p.getByRole('radio', { name: '100 m', exact: true })).first()
const radiusRow = p.getByText('How close counts as in?').locator('xpath=..')
await t.step('How close counts as in? Pick a radius, then save', radiusRow, { hold: 1200 })
await t.click(radius, { after: 300 }); await t.layer('spot', null); await sleep(300)
await t.click(p.getByRole('button', { name: 'Save place' }), { after: 1400 })
const hours = p.locator('#day-start').locator('xpath=ancestor::div[contains(@class,"grid")][1]')
await t.step('Set when the day starts and ends', hours, { hold: 1100 })
await t.click(p.getByText('Pick a time').first(), { after: 700 })
await t.click(p.getByRole('button', { name: '10:00 AM', exact: true }), { after: 700 })
await t.click(p.getByText('Pick a time').first(), { after: 700 })
await t.click(p.getByRole('button', { name: '7:00 PM', exact: true }), { after: 700 })
await t.layer('spot', null)
await t.click(p.getByRole('button', { name: 'Tue', exact: true }), { after: 600 })
const save = p.getByRole('button', { name: 'Save working hours' })
await save.scrollIntoViewIfNeeded(); await sleep(700)
await t.step('Tuesday off. Save working hours', save, { hold: 1200 })
await t.click(save, { after: 150 }); await t.layer('spot', null); await t.layer('caption', null)
await sleep(1600)
await t.layer('hidePointer')
await p.evaluate(() => window.scrollTo({ top: 0, behavior: 'smooth' })); await sleep(900)
await p.getByRole('button', { name: 'Turn off' }).scrollIntoViewIfNeeded(); await sleep(900)
await t.say('On: your team checks in at the studio from today', p.getByRole('button', { name: 'Turn off' }).locator('xpath=..'), { hold: 2800 })
await t.endCard('Attendance that marks itself')
await t.stop()
t.build()
