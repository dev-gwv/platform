import { Tutorial, studio, sleep } from './lib.mjs'
import { withSpot, padEnd, frozen, sayHere } from './helpers.mjs'
import { seedProject } from './seed-q.mjs'
import { fileURLToPath } from 'node:url'
// Run with TZ=Asia/Kolkata. PHOTO is a warm sample photo (a JPEG) to upload.
const PHOTO = process.env.PHOTO ?? fileURLToPath(new URL('./sample-photo.jpg', import.meta.url))
const t = new Tutorial('designer', { title: 'Design a premium quotation', subtitle: 'Made from your project, in your look', steps: 5 })
const s = await studio({ name: 'Mehta Studios', owner: 'Asha Mehta', skipSetup: true })
await seedProject(s)
const p = await t.open(s)
const h = withSpot(t)
await t.goto('/ai/designer')
await t.start()
await t.titleCard()
const nd = p.getByRole('button', { name: 'New design' }).last()
await t.step('Tap “New design”', nd, { hold: 900 })
await h.click(nd, { after: 300 }); await h.unspot(); await sleep(900)
const dlg = p.getByRole('dialog', { name: 'New quotation design' })
const pick = dlg.getByRole('button', { name: /No project/ }).first()
await t.step('Pick the project and a template', pick, { hold: 300 })
await h.click(pick, { after: 700 })
await h.click(p.getByRole('option', { name: /Priya & Rahul Wedding/ }).first(), { after: 300 })
await h.click(dlg.getByRole('button', { name: /Royal Indian Wedding/ }), { after: 700 })
const make = dlg.getByRole('button', { name: 'Make the design' })
await h.click(make, { after: 300 }); await h.unspot()
await p.waitForURL(/\/ai\/designer\/[^/]+$/, { timeout: 20000 })
await p.getByRole('button', { name: 'Zoom out' }).waitFor({ timeout: 60000 }); await sleep(1500)
// The whole page in view.
for (let i = 0; i < 3; i++) await t.click(p.getByRole('button', { name: 'Zoom out' }), { after: 250 })
await sleep(500)
const up = p.getByRole('button', { name: 'Upload photos' })
await t.step('Upload photos, tap a frame, then a photo', up, { hold: 300 })
await h.click(up, { after: 0 })
await p.locator('input[type=file][accept^="image"]').first().setInputFiles(PHOTO)
await sleep(2400); await h.unspot()
const frame = p.getByText('Add your photo').first()
await h.click(frame, { after: 500 })
await h.click(p.locator('button[draggable="true"]').first(), { after: 1600 })
await h.unspot()
const bg = p.getByRole('button', { name: 'Page background' }).first()
await t.step('“Background”: a colour or a gradient', bg, { hold: 300 })
await h.click(bg, { after: 700 })
const pop = p.locator('[data-radix-popper-content-wrapper]').last()
await h.click(pop.getByRole('tab', { name: 'Gradient' }), { after: 700 })
await h.click(pop.getByRole('button', { name: 'Gold dust' }), { after: 1200 })
await h.click(pop.getByRole('button', { name: 'Midnight gold' }), { after: 1400 })
await p.keyboard.press('Escape'); await h.unspot(); await sleep(800)
const tag = p.locator('[contenteditable]').filter({ hasText: 'Stories' }).first()
await t.step('Tap any text to change it', tag, { hold: 300 })
await h.click(tag, { after: 300 })
await p.keyboard.press('Control+A')
await p.keyboard.type('“Your love story, told beautifully”', { delay: 55 })
await sleep(900)
await p.mouse.click(1250, 400); await h.unspot(); await sleep(900)
await sayHere(t, 'Ready? “Send to client” or “Download PDF”', p.getByRole('button', { name: 'Send to client' }).locator('xpath=..'), 2600)
await t.endCard('A premium quotation, made from your project')
await t.stop()
padEnd(t); frozen(t); t.build()
